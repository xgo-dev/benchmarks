#!/usr/bin/env python3

import argparse
import json
import os
import re
import subprocess
import tempfile
import tomllib
from pathlib import Path


EXCLUDED_SEGMENTS = {
    "benchmark",
    "benchmarks",
    "cmd",
    "example",
    "examples",
    "integration",
    "integrations",
    "testdata",
}
EXPECTED_PACKAGES = 200


def json_stream(text):
    decoder = json.JSONDecoder()
    index = 0
    while index < len(text):
        while index < len(text) and text[index].isspace():
            index += 1
        if index == len(text):
            return
        value, index = decoder.raw_decode(text, index)
        yield value


def eligible(package):
    import_path = package.get("ImportPath", "")
    segments = import_path.split("/")
    if package.get("Error") or package.get("Name") == "main":
        return False
    if package.get("CgoFiles") or package.get("SFiles"):
        return False
    if not package.get("TestGoFiles") and not package.get("XTestGoFiles"):
        return False
    if any(segment in EXCLUDED_SEGMENTS for segment in segments):
        return False
    if "/internal/test" in import_path:
        return False
    return True


def discover(project):
    with tempfile.TemporaryDirectory(prefix="llgo-compatibility-") as temporary:
        environment = os.environ.copy()
        environment.update({"CGO_ENABLED": "0", "GOOS": "linux", "GOARCH": "amd64", "GOWORK": "off"})
        subprocess.run(["go", "mod", "init", "compatibility-probe"], cwd=temporary, env=environment, check=True, stdout=subprocess.DEVNULL)
        subprocess.run(
            ["go", "get", f"{project['Module']}@{project['Version']}"],
            cwd=temporary,
            env=environment,
            check=True,
            stdout=subprocess.DEVNULL,
        )
        completed = subprocess.run(
            ["go", "list", "-e", "-json", project["Pattern"]],
            cwd=temporary,
            env=environment,
            check=True,
            text=True,
            stdout=subprocess.PIPE,
        )
    packages = sorted(
        package["ImportPath"] for package in json_stream(completed.stdout) if eligible(package)
    )
    limit = project["Limit"]
    if len(packages) < limit:
        raise ValueError(
            f"{project['Project']} {project['Pattern']} provides {len(packages)} eligible packages, need {limit}"
        )
    return packages[:limit]


def toml_string(value):
    return json.dumps(value, ensure_ascii=False)


def render(projects):
    entries = []
    seen_names = set()
    seen_paths = set()
    for project in projects:
        for index, import_path in enumerate(discover(project), start=1):
            name = f"{project['NamePrefix']}_{index:03d}"
            if name in seen_names or import_path in seen_paths:
                raise ValueError(f"duplicate generated package: {name} {import_path}")
            seen_names.add(name)
            seen_paths.add(import_path)
            entries.append((project, name, import_path))
    if len(entries) != EXPECTED_PACKAGES:
        raise ValueError(f"generated {len(entries)} packages, want {EXPECTED_PACKAGES}")

    lines = [
        "# Code generated by ci/llgo-compatibility/generate_manifest.py; DO NOT EDIT.",
        "# Every entry has at least one Go test file on linux/amd64 and excludes",
        "# main packages, cgo, assembly, integration, examples, and testdata.",
        "",
    ]
    for project, name, import_path in entries:
        lines.extend([
            "[[Benchmarks]]",
            f"  Name = {toml_string(name)}",
            f"  Project = {toml_string(project['Project'])}",
            f"  ProjectURL = {toml_string(project['ProjectURL'])}",
            f"  Repo = {toml_string(import_path)}",
            f"  Version = {toml_string('@' + project['Version'])}",
            "  Standalone = true",
            '  Tests = "Test"',
        ])
        if project.get("BuildFlags"):
            flags = ", ".join(toml_string(flag) for flag in project["BuildFlags"])
            lines.append(f"  BuildFlags = [{flags}]")
        lines.append("")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--projects", type=Path, default=Path(__file__).with_name("projects.toml"))
    parser.add_argument("--output", type=Path, required=True)
    arguments = parser.parse_args()
    with arguments.projects.open("rb") as source:
        projects = tomllib.load(source).get("Projects", [])
    if sum(project["Limit"] for project in projects) != EXPECTED_PACKAGES:
        raise SystemExit("project limits must total exactly 200")
    arguments.output.write_text(render(projects), encoding="utf-8")


if __name__ == "__main__":
    main()
